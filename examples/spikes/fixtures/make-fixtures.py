#!/usr/bin/env python3 -I
"""Generates 12 synthetic 800x800 'product photo' fixtures (PNG, then converted to JPEG q86 with ImageMagick to keep the repo small) with no external deps.
Why synthetic: no client store assets may be used (see CLAUDE.md). Smooth gradients + grain + hard edges
are what dithering/halftone/paper shaders react to, so they are enough for the P0/P1 pixel tests.
Run: python3 -I make-fixtures.py   (from this folder)
"""
import json, math, random, struct, zlib, os

W = H = 800
OUT = os.path.dirname(os.path.abspath(__file__))

def png(path, rows):
    raw = b''.join(b'\x00' + bytes(r) for r in rows)
    def chunk(t, d): return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 6)) + chunk(b'IEND', b''))

def clamp(v): return 0 if v < 0 else 255 if v > 255 else int(v)

PALETTES = [  # (background, object, accent)
    ((236, 229, 214), (28, 32, 48), (214, 72, 40)),
    ((244, 240, 232), (196, 44, 52), (255, 212, 0)),
    ((20, 22, 26), (230, 230, 225), (0, 140, 255)),
    ((226, 236, 240), (30, 90, 160), (255, 120, 60)),
    ((248, 236, 220), (90, 60, 40), (180, 200, 80)),
    ((230, 230, 230), (40, 40, 40), (255, 0, 100)),
    ((250, 250, 245), (60, 120, 90), (240, 180, 60)),
    ((40, 36, 60), (240, 200, 180), (120, 220, 200)),
    ((235, 240, 225), (120, 40, 140), (255, 230, 90)),
    ((245, 245, 250), (20, 60, 120), (220, 40, 60)),
    ((252, 240, 230), (160, 30, 70), (40, 160, 140)),
    ((225, 232, 240), (50, 50, 60), (255, 150, 0)),
]

def make(i):
    rnd = random.Random(1000 + i)
    bg, ob, ac = PALETTES[i % len(PALETTES)]
    shape = i % 3  # 0 circle, 1 rounded rect, 2 tall bottle
    cx, cy = W * 0.5 + rnd.uniform(-40, 40), H * 0.52 + rnd.uniform(-30, 30)
    light = (rnd.uniform(-1, 1), -1.0)
    rows = []
    for y in range(H):
        row = bytearray(W * 3)
        vy = y / H
        for x in range(W):
            vx = x / W
            # backdrop: soft vertical gradient + diagonal band
            t = 1 - 0.18 * vy
            band = 0.08 if abs((vx - vy) - 0.15) < 0.07 else 0.0
            r, g, b = bg[0] * t + 255 * band, bg[1] * t + 255 * band, bg[2] * t + 255 * band
            # object mask + shading
            dx, dy = x - cx, y - cy
            if shape == 0:
                d = math.hypot(dx, dy) / 250
                inside = d < 1
                n = (dx / 250, dy / 250)
            elif shape == 1:
                ax, ay = abs(dx) - 220, abs(dy) - 180
                d = math.hypot(max(ax, 0), max(ay, 0)) - 60
                inside = d < 0
                n = (dx / 280, dy / 240)
            else:
                ax, ay = abs(dx) - 110, abs(dy) - 260
                d = math.hypot(max(ax, 0), max(ay, 0)) - 50
                inside = d < 0
                n = (dx / 160, dy / 310)
            if inside:
                shade = 0.55 + 0.45 * max(0.0, -(n[0] * light[0] + n[1] * light[1]) / 1.4)
                spec = max(0.0, 1 - math.hypot(n[0] - 0.35 * light[0], n[1] + 0.35) * 2.2) ** 3
                r, g, b = ob[0] * shade + 255 * spec * 0.6, ob[1] * shade + 255 * spec * 0.6, ob[2] * shade + 255 * spec * 0.6
                # label stripe
                if abs(dy - 40) < 28 and abs(dx) < 150:
                    r, g, b = ac
                # fine texture lines
                if (x // 3 + y // 3) % 7 == 0:
                    r, g, b = r * 0.93, g * 0.93, b * 0.93
            # shadow under the object
            sd = math.hypot(dx / 300, (dy - 230) / 60)
            if not inside and sd < 1:
                k = 1 - 0.35 * (1 - sd) ** 2
                r, g, b = r * k, g * k, b * k
            # grain
            gr = rnd.uniform(-7, 7)
            o = x * 3
            row[o], row[o + 1], row[o + 2] = clamp(r + gr), clamp(g + gr), clamp(b + gr)
        rows.append(row)
    return rows

manifest = []
for i in range(12):
    name = f'fixture-{i + 1:02d}.png'
    png(os.path.join(OUT, name), make(i))
    manifest.append({'file': name, 'width': W, 'height': H, 'alt': f'Synthetic product {i + 1}'})
    print('wrote', name)
json.dump({'note': 'Synthetic fixtures generated by make-fixtures.py (no client assets).', 'images': manifest},
          open(os.path.join(OUT, 'fixtures.json'), 'w'), indent=2)
